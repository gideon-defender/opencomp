/**
 * Generates `src/mocks/db.ts`: a browser-safe stand-in for the `@db` package.
 *
 * `@db` re-exports `@prisma/client`, whose browser entry point requires the
 * generated `.prisma/client/index-browser` bundle that only exists after
 * `prisma generate`. Components only ever read enum values at runtime, so the
 * mock reproduces every enum declared in the Prisma schema and nothing else.
 */
import fs from 'node:fs';
import path from 'node:path';
import { jsPropertyKey, jsString } from './lib/emit';

const ROOT = path.resolve(__dirname, '../../..');
const SCHEMA_DIR = path.join(ROOT, 'packages/db/prisma/schema');
const OUTPUT = path.resolve(__dirname, '../src/mocks/db.ts');

type PrismaEnum = { name: string; values: string[] };

function parseEnums(source: string): PrismaEnum[] {
  const enums: PrismaEnum[] = [];
  const pattern = /^enum\s+(\w+)\s*\{([^}]*)\}/gm;
  let match: RegExpExecArray | null;
  while ((match = pattern.exec(source)) !== null) {
    const [, name, body] = match;
    const values = body
      .split('\n')
      .map((line) => line.replace(/\/\/.*$/, '').trim())
      .filter((line) => /^\w+$/.test(line));
    if (values.length > 0) enums.push({ name, values });
  }
  return enums;
}

function collectEnums(): PrismaEnum[] {
  const files = fs.readdirSync(SCHEMA_DIR).filter((file) => file.endsWith('.prisma'));
  const enums = files.flatMap((file) => parseEnums(fs.readFileSync(path.join(SCHEMA_DIR, file), 'utf8')));
  return enums.sort((a, b) => a.name.localeCompare(b.name));
}

function render(enums: PrismaEnum[]): string {
  const blocks = enums.map(({ name, values }) => {
    const entries = values
      .map((value) => `  ${jsPropertyKey(value)}: ${jsString(value)},`)
      .join('\n');
    return `export const ${name} = {\n${entries}\n} as const;\nexport type ${name} = (typeof ${name})[keyof typeof ${name}];`;
  });

  return [
    '// GENERATED by scripts/generate-db-mock.ts — do not edit by hand.',
    '// Run `pnpm run generate` after changing the Prisma schema.',
    '',
    blocks.join('\n\n'),
    '',
    'export const Prisma = { empty: undefined } as const;',
    '',
  ].join('\n');
}

function main() {
  const enums = collectEnums();
  fs.writeFileSync(OUTPUT, render(enums));
  console.log(`Generated ${path.relative(ROOT, OUTPUT)} with ${enums.length} enums.`);
}

main();
